CREATE DATABASE IF NOT EXISTS connect4;
USE connect4;

CREATE TABLE IF NOT EXISTS games (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    status ENUM('IN_PROGRESS', 'WON', 'DRAW') NOT NULL DEFAULT 'IN_PROGRESS',
    current_player ENUM('P1', 'P2') NOT NULL DEFAULT 'P1',
    winner ENUM('P1', 'P2') NULL DEFAULT NULL,
    board_state CHAR(42) NOT NULL DEFAULT '..........................................',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS moves (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    game_id BIGINT UNSIGNED NOT NULL,
    move_number INT UNSIGNED NOT NULL,
    player ENUM('P1', 'P2') NOT NULL,
    column_idx TINYINT UNSIGNED NOT NULL,
    row_idx TINYINT UNSIGNED NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_moves_game FOREIGN KEY (game_id) REFERENCES games(id) ON DELETE CASCADE,
    CONSTRAINT uq_game_move_number UNIQUE KEY (game_id, move_number)
);